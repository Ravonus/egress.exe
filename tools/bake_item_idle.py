"""Native four-pose item hover. Pose 0 preserves the exact existing card; only the object moves."""
from pathlib import Path
import numpy as np
from PIL import Image
import bake_look as art

out=Path('src/gen/item_idle.inc')
all_data=[]
frames=[]
for phase,dy in enumerate((0,-1,0,1)):
    sheet=Image.new('RGB',(16*16,16))
    data=[]
    for k,(name,pal,rows) in enumerate(art.ITEM_ART):
        base=art.item(rows,60+k,pal in (art.PAL_FLOOR,art.PAL_OBJ))
        obj=np.array([[int(c) if c in '0123' else -1 for c in row] for row in rows.strip().splitlines()])
        if dy:
            # The slab and shadow stay fixed. Rebuild only the original object's masked pixels.
            empty=art.floor_under(60+k,pal in (art.PAL_FLOOR,art.PAL_OBJ))
            if pal not in (art.PAL_FLOOR,art.PAL_OBJ): empty[15,:]=1;empty[:,15]=1
            mask=obj>=0
            base[mask]=empty[mask]
            ys,xs=np.nonzero(mask)
            shift=max(-int(ys.min()),min(dy,14-int(ys.max())))
            for y,x in zip(ys,xs):
                assert 0 <= y+shift < 15
                base[y+shift,x]=obj[y,x]
        data.extend(b''.join(art.meta_tiles(base)))
        colors=art.BIOMES['OFFICE'][pal]
        im=Image.fromarray(np.array(colors,dtype=np.uint8)[base])
        sheet.paste(im,(k*16,0))
    all_data.append(data)
    frames.append(sheet)
text=['/* Generated by tools/bake_item_idle.py; canonical pose 0 + three native hover poses. */',
      'static const uint8_t item_idle[4][1024] = {']
for data in all_data:
    text.append('{'+','.join(str(x) for x in data)+'},')
text.append('};')
out.write_text('\n'.join(text)+'\n')
dest=Path('build/gameplay-rebuild');dest.mkdir(parents=True,exist_ok=True)
frames[0].save(dest/'item-source-idle.gif',save_all=True,append_images=frames[1:],duration=180,loop=0)
print('16 item cards, four native poses, 4096 ROM bytes; pose 0 preserved')
