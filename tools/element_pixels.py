def pixels(name):
    rows = DRAWINGS[name].strip().splitlines()
    assert len(rows) == 12 and all(len(r) == 12 for r in rows), name
    return [[0] * 16 for _ in range(2)] + [
        [0, 0] + [0 if c == '.' else int(c) for c in r] + [0, 0]
        for r in rows
    ] + [[0] * 16 for _ in range(2)]


def ground_rows(name):
    """Ground cards reserve colour 1 for their slab; outline uses colour 0."""
    return '\n'.join(''.join('.' if not c else '0' if c == 1 else str(c)
                             for c in row) for row in pixels(name))
