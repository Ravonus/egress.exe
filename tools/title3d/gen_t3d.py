        (a.host / "tex_ids.h").write_text((out / "t3d_tex.h").read_text().replace("T3D_TEX_H", "TEX_IDS_H")
                                          .replace("#endif", "extern const uint16_t T_BPAL[];\n"
                                                   "extern const uint8_t T_HUDTILES[];\n#endif"))
