    d.append(carr("T3D_FONT2", "uint8_t", font2))
    (out / "t3d_data.h").write_text("\n".join(d))

    if a.host:
        a.host.mkdir(parents=True, exist_ok=True)
        s = ["/* generated by tools/title3d/gen_t3d.py --host */", '#include "ray2.h"', ""]
