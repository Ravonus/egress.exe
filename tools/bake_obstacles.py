"""Bake the approved obstacle generator into three 24-tile sprite slots.

Each look is two 24x32 frames (glyph lit/dim), 384 bytes. No resampling:
the existing mock's native pixels, outline and checker halo are retained.
"""
from pathlib import Path
import sys

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools/mock"))
import obstacle_mock as O

NAMES = ["THE COMMUTER", "THE MOVER", "THE TRAY CART", "THE DRAIN", "THE DUPLICATE",
         "THE TOPIARY", "POWER CUT", "REORG", "REPLY ALL", "STANDBY"]
SOURCE = [0, 1, 2, 3, 4, 5, 5, 4, 0, 1]


def rgb555(c):
    return (c[0] >> 3) | ((c[1] >> 3) << 5) | ((c[2] >> 3) << 10)


def bake():
    data, pals = [], []
    sheet = Image.new("RGB", (10 * 52, 40), O.INK)
    for rule, src in enumerate(SOURCE):
        beh, _, _, original, dark, glyph = O.SIX[src]
        fields = dict(original)
        # The M mover's silhouette is reused at its native small size, never scaled.
        fields["size"] = 1
        if rule == 9:
            glyph = "LOCK"
        lk = O.look(fields, O.M.mix_seed(0x0B57, rule))
        frames = [O.obstacle_image(lk, beh, dark, glyph, on, W=64, H=64) for on in (True, False)]
        boxes = [im.getbbox() for im in frames]
        x0, y0 = min(b[0] for b in boxes), min(b[1] for b in boxes)
        x1, y1 = max(b[2] for b in boxes), max(b[3] for b in boxes)
        assert x1 - x0 <= 24 and y1 - y0 <= 32, (rule, (x0, y0, x1, y1))
        ramp = O.DARKBODY if dark else O.CHROME_ALT.get(fields["fam"], O.CHROME[fields["fam"]])
        palette = [O.INK, ramp[1], O.E.WHITE]
        pals.append([0] + [rgb555(c) for c in palette])
        look = bytearray()
        for f, im in enumerate(frames):
            native = Image.new("RGBA", (24, 32))
            native.alpha_composite(im.crop((x0, y0, x1, y1)), ((24 - (x1 - x0)) // 2, 32 - (y1 - y0)))
            pixels = []
            preview = Image.new("RGB", (24, 32), (176, 150, 200))
            for y in range(32):
                row = []
                for x in range(24):
                    c = native.getpixel((x, y))
                    v = 0 if c[3] == 0 else 1 + min(range(3), key=lambda i: sum((c[k] - palette[i][k]) ** 2 for k in range(3)))
                    row.append(v)
                    if v:
                        preview.putpixel((x, y), palette[v - 1])
                pixels.append(row)
            sheet.paste(preview, (rule * 52 + f * 26, 0))
            # GBC 8x16 sprite order: each row of three columns is six tiles.
            for by in (0, 16):
                for bx in (0, 8, 16):
                    for y in range(by, by + 16):
                        lo = hi = 0
                        for x in range(8):
                            v = pixels[y][bx + x]
                            lo |= (v & 1) << (7 - x)
                            hi |= (v >> 1) << (7 - x)
                        look.extend((lo, hi))
        assert len(look) == 384
        data.append(look)
    h = ROOT / "src/gen/obstacle_art.h"
    h.write_text('''/* Generated by tools/bake_obstacles.py. */
#ifndef OBSTACLE_ART_H
#define OBSTACLE_ART_H
#include <gb/gb.h>
void obstacle_art_load(uint8_t rule, uint8_t slot) BANKED;
void obstacle_art_name(uint8_t rule) BANKED;
#endif
''')
    lines = ['/* Generated by tools/bake_obstacles.py; approved native obstacle parts. */', '#pragma bank 255',
             '#include "play.h"', '#include "gen/obstacle_art.h"', 'static const uint8_t tiles[10][384] = {']
    for look in data:
        lines.append('  {')
        for i in range(0, 384, 16):
            lines.append('    ' + ','.join(f'0x{v:02x}' for v in look[i:i + 16]) + ',')
        lines.append('  },')
    lines += ['};', 'static const uint16_t palettes[10][4] = {']
    lines += ['  {' + ','.join(f'0x{c:04x}' for c in pal) + '},' for pal in pals]
    lines += ['};', 'static const char names[10][15] = {']
    lines += ['  "' + n + '",' for n in NAMES]
    lines += ['};', '''void obstacle_art_load(uint8_t rule, uint8_t slot) BANKED {
  uint8_t p = slot == 2u ? 5u : (uint8_t)(2u + slot), i;
  if (rule >= 10u || slot >= 3u) return;
  VBK_REG = 0;
  set_sprite_data((uint8_t)(16u + 24u * slot), 24u, tiles[rule]);
  for (i = 0; i != 4u; i++) pal_sp[p * 4u + i] = palettes[rule][i];
  pal_dirty = 1;
}
void obstacle_art_name(uint8_t rule) BANKED {
  if (rule < 10u) hud_msg(names[rule]);
}''']
    (ROOT / 'src/gen/obstacle_art.c').write_text('\n'.join(lines) + '\n')
    sheet.save(ROOT / 'docs/shots/b2_obstacles_native.png')
    print('10 native obstacle looks, 3840 tile bytes, three slots of 24 tiles')


if __name__ == '__main__':
    bake()
