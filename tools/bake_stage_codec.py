"""Validate the hand-authored stage codec and emit its compact native tables."""
import argparse, json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
GOALS=('load','heat','cold','power','portal')
CONDS=('hold','latch','either','both')
SHAPES=('terraces','basins','bend','courts')
SIZES=('xs','s','m','l','xl','xxl')
BIOMES=('office','vents','atrium','servers','foodcourt','garden','rooftop','glitch')
ALTS=('push','craft','jump')
def mask(values, names):
    assert values and len(set(values))==len(values),values
    assert all(v in names for v in values),values
    return sum(1<<names.index(v) for v in values)
def compile_codec(data):
    assert data['version']==1
    assert tuple(s['name'] for s in data['sizes'])==SIZES
    assert len(data['stages'])==6
    assert tuple(b['name'] for b in data['biomes'])==BIOMES
    rows=[]
    for s in data['sizes']:
        a,b=s['width'];c,d=s['height'];lo,hi=s['goals']
        assert 16<=a<=b<=128 and a%4==b%4==0
        assert 14<=c<=d<=54 and (c-14)%4==(d-14)%4==0
        assert 1<=lo<=hi<=4 and (a-6)//lo>=10
        rows.append((a,b,c,d,lo,hi))
    rules=[]
    for r in data['stages']:
        goals=mask(r['goals'],GOALS);required=mask(r['required'],GOALS) if r.get('required') else 0
        assert required&goals==required and required.bit_count()<=2
        assert all(data['sizes'][SIZES.index(s)]['width'][1]>=6+required.bit_count()*10 for s in r['sizes'])
        # Transport is causal: it always requires a preceding load.
        assert not goals&(1<<4) or required==((1<<0)|(1<<4))
        alts=mask(r['alternatives'],ALTS)
        assert not goals&1 or alts&3==3
        rules.append((goals,mask(r['conditions'],CONDS),mask(r['shapes'],SHAPES),
                      mask(r['sizes'],SIZES),alts,required))
    biomes=[]
    for b in data['biomes']:
        row=tuple(b[k] for k in ('foliage','water','props','water_style'))
        assert all(isinstance(v,int) and 0<=v<=255 for v in row[:3]) and 0<=row[3]<=3
        biomes.append(row)
    def table(name,rows):
        return 'static const uint8_t '+name+f'[{len(rows)}][{len(rows[0])}] = {{\n'+''.join('  {'+','.join(str(v)+'u' for v in row)+'},\n' for row in rows)+'};\n'
    return ('/* Generated by tools/bake_stage_codec.py from assets/stages/codec.json. */\n'
            +table('land_sizes',rows)+table('land_rules',rules)+table('land_biomes',biomes))
def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');a=ap.parse_args()
    text=compile_codec(json.loads((ROOT/'assets/stages/codec.json').read_text()))
    path=ROOT/'src/gen/stage_codec.inc'
    if a.check:assert path.read_text()==text,'stage codec tables are stale'
    else:path.write_text(text)
if __name__=='__main__':main()
