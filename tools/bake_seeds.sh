#!/bin/sh
# Bake the accepted-seed table: for every tier, the PER lowest seeds whose rooms generate, are not trivial (a keycard
# or the door reachable without moving anything) and the solver solves within the tier's bounds. Each tier is split
# over JOBS interleaved seed streams that run in parallel; the merged, sorted list keeps its first PER seeds.
# Usage: sh tools/bake_seeds.sh EGTOOL OUT.c [PER] [JOBS]
set -eu
EGTOOL="$1"; OUT="$2"; PER="${3:-128}"; JOBS="${4:-3}"; TIERS=6
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
t=0; while [ $t -lt $TIERS ]; do
  j=0; while [ $j -lt "$JOBS" ]; do
    nice "$EGTOOL" tier $t "$PER" $((j + 1)) "$JOBS" > "$TMP/$t.$j.txt" 2> "$TMP/$t.$j.log" &
    j=$((j+1))
  done
  t=$((t+1))
done
wait
cat "$TMP"/*.log >&2
{
  echo "/* Generated by tools/bake_seeds.sh (host/egtool tier): seeds the solver accepted, per tier. Do not edit. */"
  echo "#pragma bank 255"
  echo "#include <gb/gb.h>"
  echo "#include <stdint.h>"
  echo "#include \"eg_seeds.h\""
  echo "static const uint16_t table[$TIERS][$PER] = {"
  t=0; while [ $t -lt $TIERS ]; do
    cat "$TMP/$t".*.txt | sort -n | head -n "$PER" > "$TMP/$t.all"
    [ "$(wc -l < "$TMP/$t.all")" -eq "$PER" ] || { echo "tier $t short" >&2; exit 3; }
    printf '  {'; awk '{printf "%s%s", (NR>1?",":""), (NR%12==1?"\n    ":" ") $1}' "$TMP/$t.all"; echo '},'
    t=$((t+1))
  done
  echo "};"
  echo "uint16_t eg_seed_pick(uint8_t tier, uint8_t k) BANKED { return table[tier][k & ($PER - 1)]; }"
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
