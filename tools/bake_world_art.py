"""Native environment cards; reuse world-only slots without growing VRAM or metadata RAM."""
from pathlib import Path
import numpy as np
from PIL import Image
import bake_look as L
import bake_art as A

ROOT=Path(__file__).resolve().parents[1]
NAMES=('FERN0','FERN1','FLOWER0','FLOWER1','REED0','REED1','PROP0','PROP1','RIVER0','RIVER1','FALL0','FALL1')
IDS=(31,33,35,38,39,40,41,42,43,44,45,46)
PALS=(1,1,6,6,1,1,6,6,4,4,4,4)
def plant(kind,variant,phase,style):
    a=L.floor_under(83+variant,False);sway=phase if variant else -phase
    if kind==0:
        if not variant:  # planted seed: a visible soil mound and breathing shoot
            a[11:14,4:12]=0;a[11,5:11]=2;a[12,5:11:2]=3
            a[8:12,8]=0;a[8+phase,7:10]=3
            return a.astype(np.uint8)
        # Small tree: trunk, separate crown clusters and idle leaf sway.
        a[7:14,7:10]=0;a[9:14,8]=2
        for x,y in ((5+sway,5),(9+sway,3),(11,6)):
            for yy in range(y-2,y+3):
                for xx in range(x-2,x+3):
                    if abs(xx-x)+abs(yy-y)<=3:a[yy,xx]=3 if xx<x else 2
        a[5,7+sway]=0;a[7,11]=0
        return a.astype(np.uint8)
    elif kind==1:
        if variant:  # spent tree: stump, ash and sparse drifting embers
            a[11:14,6:11]=0;a[11,6:11]=2;a[12,7:10]=3
            a[13,3:14:2]=0;a[9-phase,5+phase]=2
            return a.astype(np.uint8)
        a[7:14,8]=0;a[6+phase,4:8]=3;a[8-phase,9:13]=2
        a[7+phase,5:8]=2;a[9-phase,9:12]=3
        return a.astype(np.uint8)
    for x,y in ((4,5),(8,3),(11,6)):
        a[y:13,x]=0;a[y:12,x+1]=2
        a[y-1:y+2,x+sway]=3
        a[11,x-2:x+1]=2
    if style==3:a[3+variant,3:6]=3
    return a.astype(np.uint8)
def prop(variant,phase,style):
    a=L.floor_under(91,True)
    if not variant:
        a[4:12,3:13]=0;a[3,4:12]=3;a[4:10,4:12]=2;a[5:9,5:11]=0
        for y in (5,7):a[y,5+phase:10:2]=3
        a[11:14,7:9]=0;a[13,5:11]=3
    else:
        a[7:13,4:12]=0;a[5:8,5:11]=3;a[8:12,5:11]=2
        a[6:13,7]=0;a[9,8:11]=3;a[11,9]=3 if phase else 0
    return a.astype(np.uint8)
def water(fall,variant,phase,style):
    y,x=np.mgrid[:16,:16];a=np.full((16,16),2,dtype=np.uint8)
    if style in (2,3):
        a[((x+variant*4)%8)<2]=0
        a[(((y+phase*3+x//4)%8)<2)&((x%4)==1)]=3
        a[((x+y+phase*2)%16)==0]=1 if style==2 else 0
        if fall:a[((y+phase*4)%8)==0]=3
    elif fall:
        a[((x+variant*2)%7)==0]=0;a[((x+variant)%5)==0]=3
        a[((y+phase*3+x//3)%8)==0]=3
    else:
        a[((y+phase*2+(x//4)%2)%8)==0]=3
        a[((x+y+variant*3)%16)==0]=0
        a[(((x-y+phase)%8)==0)&((x%4)==0)]=1
    return a
def cards(style,phase):
    return [plant(k//2,k&1,phase,style) if k<6 else prop(k&1,phase,style) if k<8 else water(k>=10,k&1,phase,style) for k in range(12)]
def main():
    ms,*_=L.layout()
    assert all(not ms[k][1]&0x80 and isinstance(ms[k][3],int) for k in IDS)
    out=ROOT/'src/gen';tiles=b''.join(b''.join(L.meta_tiles(a)) for s in range(4) for f in range(2) for a in cards(s,f))
    h=['/* Generated by tools/bake_world_art.py. */','#ifndef WORLD_ART_H','#define WORLD_ART_H','#include <gb/gb.h>','#include <stdint.h>']
    h += [f'#define M_WORLD_{name} {n}u'for name,n in zip(NAMES,IDS)]
    h += ['void world_art_load(uint8_t style,uint8_t *meta_pal,const uint8_t *meta_tiles,uint16_t *pal_bg) BANKED;',
          'void world_art_tick(const uint8_t *meta_tiles,uint16_t frame) BANKED;',
          'void environment_art_load(uint8_t *meta_pal,const uint8_t *meta_tiles) BANKED;',
          'void environment_art_tick(const uint8_t *meta_tiles,uint16_t frame) BANKED;','#endif']
    (out/'world_art.h').write_text('\n'.join(h)+'\n')
    c=['/* Generated by tools/bake_world_art.py. */','#pragma bank 255','#include <gb/gb.h>','#include <gb/cgb.h>','#include "world_art.h"',A.c_bytes('world_idle',tiles),
       'static const uint8_t ids[12]={'+','.join(map(str,IDS))+'};','static const uint8_t pals[12]={'+','.join(map(str,PALS))+'};','static uint8_t world_style;',
       '''static void upload(uint8_t k,uint8_t phase,const uint8_t *meta_tiles) {
  uint16_t off=((uint16_t)world_style*24u+(uint16_t)phase*12u+k)*64u;
  VBK_REG=1u;set_bkg_data(meta_tiles[(uint16_t)ids[k]*4u],4u,world_idle+off);VBK_REG=0u;
}
void world_art_load(uint8_t style,uint8_t *meta_pal,const uint8_t *meta_tiles,uint16_t *pal_bg) BANKED {
  uint8_t k;world_style=style&3u;
  for(k=0u;k<12u;k++) {meta_pal[ids[k]]=pals[k];upload(k,0u,meta_tiles);}
  if(world_style==2u) {pal_bg[18]=RGB(3,26,21);pal_bg[19]=RGB(25,31,29);}
  if(world_style==3u) {pal_bg[18]=RGB(27,5,28);pal_bg[19]=RGB(5,31,30);}
}
void world_art_tick(const uint8_t *meta_tiles,uint16_t frame) BANKED {
  if(!(frame&3u))upload((uint8_t)(8u+((frame>>2)&3u)),(uint8_t)((frame>>4)&1u),meta_tiles);
  else if((frame&7u)==2u)upload((uint8_t)((frame>>3)&7u),(uint8_t)((frame>>6)&1u),meta_tiles);
}
void environment_art_load(uint8_t *meta_pal,const uint8_t *meta_tiles) BANKED {
  uint8_t k;world_style=0u;
  for(k=0u;k<4u;k++){meta_pal[ids[k]]=pals[k];upload(k,0u,meta_tiles);}
}
void environment_art_tick(const uint8_t *meta_tiles,uint16_t frame) BANKED {
  if((frame&15u)==2u)upload((uint8_t)((frame>>4)&3u),(uint8_t)((frame>>6)&1u),meta_tiles);
}
''']
    (out/'world_art.c').write_text('\n'.join(c))
    sheet=Image.new('RGB',(384,64),'#140e2e')
    for style in range(4):
        for phase in range(2):
            for k,a in enumerate(cards(style,phase)):
                pal=L.BIOMES['SERVERS' if style==2 else 'GLITCH' if style==3 else 'GARDEN'][PALS[k]]
                rgb=np.asarray(pal,dtype=np.uint8)[a];sheet.paste(Image.fromarray(rgb),(phase*192+k*16,style*16))
    target=ROOT/'docs/shots/world_environment.png';sheet.resize((1536,256),Image.Resampling.NEAREST).save(target)
    print('world art: 12 existing card slots, 4 styles, 2 poses, 6144 ROM bytes; no new VRAM, OAM or metadata RAM')
if __name__=='__main__':main()
