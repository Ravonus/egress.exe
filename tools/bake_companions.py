"""Compile the editable critter role/ability matrix into bounded native data."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]


def generate():
 source=json.loads((ROOT/'assets/alchemy/companions.json').read_text())
 catalogue=json.loads((ROOT/'assets/alchemy/catalogue.json').read_text())
 pets=source['companions'];assert len(pets)==12
 roles={'ATTACK','HEAL','SUPPORT','TANK','DOT','TACTIC'}
 actions={'STRIKE','BURN','HEAL','CLEANSE','HASTE','PUSH','TAUNT','BRACE','SHOCK','CHAIN','SLOW','FREEZE','GUARD','BURN_FIELD','WARD','BLIND','REGEN','ROOT','EXPOSE','REFLECT'}
 rows=[];names=[]
 for k,p in enumerate(pets):
  assert p['name']==catalogue['pets'][k][1]
  assert p['role'] in roles and p['automatic'] in actions and p['command'] in actions
  assert 4<=p['hp']<=20 and p['armour'] in (0,1)
  assert all(1<=p[n]<=225 for n in ('autoCooldown','commandCooldown'))
  assert 1<=p['autoStamina']<p['commandStamina']<=32
  assert 24<=p['range']<=64
  assert all(len(p[n])<=18 for n in ('automaticName','commandName'))
  assert set(p['traits'])<= {'SECOND_SPRING'}
  values=['PR_'+p['role'],'PA_'+p['automatic'],'PA_'+p['command']]+[str(p[n])+'u' for n in ('hp','armour','autoCooldown','commandCooldown','autoStamina','commandStamina','range')]+['PT_SECOND_SPRING' if 'SECOND_SPRING' in p['traits'] else '0u']
  rows.append('{'+','.join(values)+'}')
  names.append('{'+','.join(json.dumps(p[n]) for n in ('automaticName','commandName'))+'}')
 assert {p['role'] for p in pets}==roles
 return '/* Generated by tools/bake_companions.py. */\nstatic const eg_pet_profile profiles[12]={\n'+',\n'.join(rows)+'\n};\nstatic const char ability_names[12][2][19]={\n'+',\n'.join(names)+'\n};\n'


if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();path=ROOT/'src/core/eg_pet_data.inc';data=generate()
 if a.check:assert path.read_text()==data,'Run tools/bake_companions.py'
 else:path.write_text(data)
 print('Twelve critters cover tanks, healers, attackers, supports, damage over time and tactics; 24 named abilities.')
