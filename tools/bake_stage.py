"""Bake the B2 stage cards: the temp (the escort, walking away from you, two steps) and the shopkeeper (the heist,
facing you), as BG cards for VRAM bank 0's BG-only block (0x9000, ids STAGE_T0..STAGE_T0+11).

    python tools/bake_stage.py src/gen [--sheet docs/shots/b2_stage_cards.png]

One palette, the floor's REACT_B row repainted per stage (src/stage.c): 0 ink (outline and hair), 1 the slab base
(the card sits on the floor without a seam), 2 skin, 3 clothes. The skin and the clothes are seeded per stage from
the run's people palettes (art_skins, art_hoodies), so every temp and shopkeeper is somebody different.
Each card is 4 tiles in row-major order (TL, TR, BL, BR), written as static data into src/gen/stage_art.h (only
src/stage.c includes it, so the data sits in that module's bank)."""

from __future__ import annotations

import sys
from pathlib import Path

STAGE_T0 = 116  # BG-only block ids 116..127 (rules: 84..127 free; b2-stages takes the top 12)

# o ink, . slab, s skin, c clothes, l lanyard (ink on clothes)
FRONT = [
    "................",
    ".....oooooo.....",
    "....oooooooo....",
    "...oooooooooo...",
    "...oossssssoo...",
    "...ossossosso...",
    "...osssssssso...",
    "....ossoosso....",
    ".....oossoo.....",
    "...ooccssccoo...",
    "..occccllcccco..",
    "..occocllcocco..",
    "..osoccccccoso..",
    "...ooccccccoo...",
    "....occo..occo..",
    "....oooo..oooo..",
]
BACK_A = [
    "................",
    ".....oooooo.....",
    "....oooooooo....",
    "...oooooooooo...",
    "...oooooooooo...",
    "...oooooooooo...",
    "...osooooooso...",
    "....ooooooo.....",
    ".....oossoo.....",
    "...ooccccccoo...",
    "..occcccccccco..",
    "..occoccccocco..",
    "..osocccccccso..",
    "...ooccccccoo...",
    "....occo.oo.....",
    "....ooo.........",
]
BACK_B = [row for row in BACK_A[:14]] + [
    ".....oo.occo....",
    ".........ooo....",
]
CARDS = {"FRONT": FRONT, "BACK_A": BACK_A, "BACK_B": BACK_B}
VAL = {"o": 0, ".": 1, "s": 2, "c": 3, "l": 0}


def tile_bytes(rows: list[str], tx: int, ty: int) -> list[int]:
    out = []
    for y in range(8):
        lo = hi = 0
        for x in range(8):
            v = VAL[rows[ty * 8 + y][tx * 8 + x]]
            lo |= (v & 1) << (7 - x)
            hi |= ((v >> 1) & 1) << (7 - x)
        out += [lo, hi]
    return out


def main() -> int:
    out = Path(sys.argv[1])
    sheet = None
    if "--sheet" in sys.argv:
        sheet = Path(sys.argv[sys.argv.index("--sheet") + 1])
    data: list[int] = []
    for rows in CARDS.values():
        assert len(rows) == 16 and all(len(r) == 16 for r in rows), rows
        for ty in range(2):
            for tx in range(2):
                data += tile_bytes(rows, tx, ty)
    lines = [
        "/* generated by tools/bake_stage.py: the B2 stage cards (the temp, the shopkeeper). Do not edit. */",
        "#ifndef EG_STAGE_ART_H",
        "#define EG_STAGE_ART_H",
        f"#define STAGE_T0 {STAGE_T0}u /* BG-only block (VRAM bank 0, 0x9000): ids STAGE_T0 .. STAGE_T0 + 11 */",
        "#define STAGE_CARD_FRONT 0u",
        "#define STAGE_CARD_BACK_A 1u",
        "#define STAGE_CARD_BACK_B 2u",
        f"#define STAGE_CARDS {len(CARDS)}u",
        "static const uint8_t stage_card_tiles[STAGE_CARDS * 64u] = {",
    ]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines += ["};", "#endif", ""]
    (out / "stage_art.h").write_text("\n".join(lines))
    if sheet:
        from PIL import Image

        skins = [(255, 219, 172), (241, 194, 125), (224, 172, 105), (198, 134, 66), (141, 85, 36), (92, 56, 32)]
        clothes = [(70, 110, 200), (200, 90, 70), (80, 160, 110), (230, 180, 60), (150, 90, 180), (60, 60, 70)]
        img = Image.new("RGB", (len(CARDS) * 18 * len(skins), 18), (40, 30, 50))
        px = img.load()
        for k, (sk, cl) in enumerate(zip(skins, clothes)):
            for c, rows in enumerate(CARDS.values()):
                ox = (k * len(CARDS) + c) * 18 + 1
                for y, row in enumerate(rows):
                    for x, ch in enumerate(row):
                        v = VAL[ch]
                        px[ox + x, 1 + y] = [(24, 16, 32), (176, 150, 200), sk, cl][v]
        sheet.parent.mkdir(parents=True, exist_ok=True)
        img.resize((img.width * 4, img.height * 4), Image.NEAREST).save(sheet)
    print(f"stage cards: {len(CARDS)} ({len(data)} bytes, tiles {STAGE_T0}..{STAGE_T0 + 4 * len(CARDS) - 1})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
