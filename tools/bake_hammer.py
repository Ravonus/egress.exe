"""Bake the hammer's native wind-up/contact poses into the existing weapon slots."""
from pathlib import Path
from PIL import Image,ImageDraw
import sys
import numpy as np
sys.path.insert(0,str(Path(__file__).parent))
import bake_art as art

def pose(direction,impact):
    im=Image.new('P',(16,16));d=ImageDraw.Draw(im)
    # A short dark grip and a broad, rim-lit steel head: visibly a hammer,
    # rather than the blade's cable crescent. Contact lowers the head.
    d.line((7,14,9 if impact else 6,5),fill=1,width=3)
    d.line((7,13,9 if impact else 6,6),fill=2,width=1)
    x,y=(4,6) if impact else (1,1)
    d.rectangle((x,y,x+10,y+5),fill=1)
    d.rectangle((x+1,y+1,x+9,y+4),fill=2)
    d.line((x+1,y+1,x+8,y+1),fill=3)
    d.line((x+2,y+2,x+2,y+4),fill=3)
    if impact:
        d.point((2,12),fill=3);d.line((11,13,14,12),fill=3)
    if direction=='up':im=im.transpose(Image.Transpose.FLIP_TOP_BOTTOM)
    elif direction=='side':im=im.transpose(Image.Transpose.ROTATE_90)
    elif direction=='diagonal':im=im.rotate(-45,resample=Image.Resampling.NEAREST)
    return im

def encode(im):
    return b''.join(art.encode(np.asarray(im.crop((x,y,x+8,y+8)))) for x,y in [(0,0),(0,8),(8,0),(8,8)])
# Down/up/side match ST_ARC_DOWN, UP, SIDE, with four tiles per pose.
raw=b''.join(encode(pose(direction,impact)) for direction in ('down','up','side') for impact in (False,True))
diag=encode(pose('diagonal',True))
out=Path('src/gen/hammer.inc')
out.write_text('/* Generated by tools/bake_hammer.py. Existing weapon VRAM slots, no extra RAM. */\n'+art.c_bytes('hammer_arc',raw).replace('const uint8_t','static const uint8_t')+'\n'+art.c_bytes('hammer_diagonal',diag).replace('const uint8_t','static const uint8_t')+'\n')
