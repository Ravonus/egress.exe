"""CRC linear contributions for a changed byte in the 256-byte run record."""
from pathlib import Path
import argparse
ROOT=Path(__file__).resolve().parents[1]


def crc(data):
 c=0
 for x in data:
  c^=x<<8
  for _ in range(8):c=((c<<1)^(0x1021 if c&0x8000 else 0))&65535
 return c


def generated():
 text='/* Generated by tools/bake_journal_patch.py: 5824 ROM bytes. */\n'
 for size in (256,112):
  rows=[[crc(bytes([1<<bit])+bytes(size-3-offset)) for bit in range(8)] for offset in range(size-2)]
  text+='static const uint16_t patch_bits'+str(size)+'['+str(size-2)+'][8]={\n'+',\n'.join('{'+','.join(hex(n)+'u' for n in r)+'}' for r in rows)+'\n};\n'
 return text


if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();out=ROOT/'src/core/eg_journal_patch.inc';s=generated()
 if a.check:assert out.read_text()==s
 else:out.write_text(s)
