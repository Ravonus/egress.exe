"""Generate the cartridge sky tables from fit.json and events.json (host only).

    .venv/bin/python proto/sky/gen_tables.py           # -> proto/sky/out/sky_tab.c, sky_ev_*.c, sky_ev.h, tables.json

- sky_tab.c (one bank, or bank 0 on the host): the quarter sine (2049 x int16, Q14), the octant arctangent
  (1025 x uint16), the mean angles (u32 constant, u32 per day, u32 per minute, in 2^32 per turn), the series terms
  and the body descriptors. Terms under PRUNE degrees are dropped (they are measured in verify.py).
- sky_ev_b<N>.c: the event streams, packed first-fit into 16 KiB ROM banks (each stream is whole in one bank), and
  sky_ev.c, the stream descriptors (bank 0). Encoding, per stream: n deltas of `width` bytes, little-endian, plus a
  bias; with `flag` the top bit of a delta is a flag (an ingress going backward). An index entry every 32 events: the
  absolute minute of the block's first event (u32, minutes since 2026-01-01 00:00 UTC) and its state byte (the
  quarter, 1 for a retrograde station, or the sign entered). The first delta of each block is not stored twice: the
  index holds it.
- marks: (u16 phase-event index, u8 flags, i8 minutes from the phase to the eclipse's greatest moment), sorted.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

OUT = Path(__file__).parent / "out"
PRUNE = 0.012  # degrees; terms smaller than this are dropped
RPRUNE = 0.0004  # AU
BLOCK = 32
BANK0 = 8  # first ROM bank for the event streams in the prototype ROM (the code sits in banks 0..7 at most)
U = 65536.0 / 360.0  # 16-bit binary angle per degree
U32 = 4294967296.0 / 360.0
M2026 = 9497 * 1440
BODIES = ["EARTH", "MOON", "MERCURY", "VENUS", "MARS", "JUPITER", "SATURN"]
PLANETS = ["MERCURY", "VENUS", "MARS", "JUPITER", "SATURN", "URANUS", "NEPTUNE", "PLUTO"]


def u32(deg: float) -> int:
    return int(round((deg % 360.0) * U32)) & 0xFFFFFFFF


def c_arr(ctype: str, name: str, vals: list[int], per: int = 16, static: bool = False) -> str:
    body = ",\n  ".join(", ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per))
    return f"{'static ' if static else ''}const {ctype} {name}[{len(vals)}] = {{\n  {body}\n}};\n"


def series_tables(fit: dict) -> tuple[str, dict]:
    angles = dict(fit["angles"])
    # GMST (Meeus 12.4) at 2000-01-01 00:00 UT, deg/day; the building's meridian is the shared world's 0
    angles["GMST"] = [(280.46061837 - 0.5 * 360.98564736629) % 360.0, 360.98564736629]
    names: list[str] = []
    outs = {}
    for b in BODIES:
        f = fit[b]
        a0, r = angles[f["L"]]
        # fold the fitted constant and linear drift into the body's own output angle
        outs[b] = (a0 + f["c0"] - f["c1"] * 2.7, r + f["c1"] / 10000.0)
    rows = []
    for nm, (a0, r) in list(angles.items()) + [("OUT_" + b, v) for b, v in outs.items()]:
        names.append(nm)
        rows.append((u32(a0), u32(r), u32(r / 1440.0)))
    idx = {n: i for i, n in enumerate(names)}
    terms: list[tuple] = []
    desc = []
    info: dict = {"pruned": {}}
    for b in BODIES:
        f = fit[b]
        t0 = len(terms)
        kept = dropped = 0.0
        for t in sorted(f["lon"], key=lambda t: -t["amp"]):
            if t["amp"] < PRUNE:
                dropped += t["amp"]
                continue
            ar = [(idx[n], k) for n, k in t["arg"].items() if k]
            assert len(ar) <= 3, (b, t)
            ar += [(0, 0)] * (3 - len(ar))
            terms.append((ar, int(round(t["ph"] * U)) & 0xFFFF, int(round(t["amp"] * U * 4))))  # x4: the sum is taken >> 16
            kept += 1
        nl = len(terms) - t0
        r0 = rq = 0
        tr = len(terms)
        if "rad" in f:
            r0 = int(round((f["r0"] - f["r1"] * 2.7) * 2048))  # Q11 AU
            for t in sorted(f["rad"], key=lambda t: -t["amp"]):
                if t["amp"] < RPRUNE:
                    continue
                ar = [(idx[n], k) for n, k in t["arg"].items() if k]
                ar += [(0, 0)] * (3 - len(ar))
                terms.append((ar, int(round(t["ph"] * U)) & 0xFFFF, int(round(t["amp"] * 8192))))  # Q11 x4
        nr = len(terms) - tr
        desc.append((idx["OUT_" + b], t0, nl, tr, nr, r0))
        info["pruned"][b] = round(dropped, 4)
    src = ["/* generated by gen_tables.py: the live sky's mean angles, series and lookup tables. Do not edit. */",
           '#include "sky.h"', ""]
    sinq = [int(round(math.sin(i * math.pi / 4096.0) * 16384)) for i in range(2049)]
    atn = [int(round(math.degrees(math.atan(i / 1024.0)) * U)) for i in range(1025)]
    src.append(c_arr("int16_t", "sky_sinq", sinq))
    src.append(c_arr("uint16_t", "sky_atan", atn))
    src.append(f"const uint32_t sky_ang0[{len(rows)}] = {{{', '.join(f'{r[0]}ul' for r in rows)}}};")
    src.append(f"const uint32_t sky_angd[{len(rows)}] = {{{', '.join(f'{r[1]}ul' for r in rows)}}};")
    src.append(f"const uint32_t sky_angm[{len(rows)}] = {{{', '.join(f'{r[2]}ul' for r in rows)}}};")
    src.append(f"const sky_term sky_terms[{len(terms)}] = {{")
    for ar, ph, amp in terms:
        assert -32768 <= amp <= 32767
        src.append(f"  {{{ar[0][0]}, {ar[0][1]}, {ar[1][0]}, {ar[1][1]}, {ar[2][0]}, {ar[2][1]}, {ph}u, {amp}}},")
    src.append("};")
    src.append(f"const sky_body sky_bodies[{len(desc)}] = {{")
    for d in desc:
        src.append(f"  {{{d[0]}, {d[1]}, {d[2]}, {d[3]}, {d[4]}, {d[5]}}},")
    src.append("};")
    hdr = [f"#define SKY_NANG {len(rows)}", f"#define SKY_ANG_NODE {idx['NODE']}", f"#define SKY_ANG_GMST {idx['GMST']}"]
    info.update(nang=len(rows), nterms=len(terms), angle_names=names)
    return "\n".join(src) + "\n", {"hdr": hdr, **info}


def le(v: int, w: int) -> list[int]:
    return [(v >> (8 * i)) & 0xFF for i in range(w)]


def stream(name: str, kind: int, evs: list[tuple[int, int, int]], state0: int, flagged: bool) -> dict:
    """evs: (minute since 2000, state, flag). Picks the narrowest width and a bias; returns bytes and stats."""
    ms = [e[0] - M2026 for e in evs]
    gaps = [b - a for a, b in zip(ms, ms[1:])] or [0]
    bias = min(gaps) if not flagged else 0
    span = max(gaps) - bias
    width = 2 if span < (1 << (15 if flagged else 16)) else 3 if span < (1 << (23 if flagged else 24)) else 4
    if width == 2 and not flagged and span < 65536:
        pass
    top = 1 << (8 * width - 1)
    dat: list[int] = []
    idx: list[int] = []
    for i, e in enumerate(evs):
        if i % BLOCK == 0:
            idx += le(ms[i], 4) + [e[1] & 0xFF]
            d = 0
        else:
            d = ms[i] - ms[i - 1] - bias
        if flagged and e[2]:
            d |= top
        assert 0 <= d < (1 << (8 * width)), (name, d, width)
        dat += le(d, width)
    return dict(name=name, kind=kind, n=len(evs), width=width, flag=int(flagged), bias=bias, state0=state0,
                idx=idx, dat=dat, bytes=len(idx) + len(dat))


def event_tables(ev: dict) -> tuple[list[dict], list[int]]:
    S = []
    S.append(stream("phase", 0, [(m, q, 0) for m, q in ev["phases"]], (ev["phases"][0][1] - 1) & 3, False))
    S.append(stream("perigee", 1, [(m, 0, 0) for m, _ in ev["perigee"]], 0, False))
    for p in PLANETS:
        st = ev["stations"][p]
        S.append(stream("st_" + p.lower(), 2, [(m, 1 if k == "R" else 0, 0) for m, k in st],
                        ev["start"][p][1], False))
    for b in ["SUN"] + PLANETS:
        ing = ev["ingress"][b]
        S.append(stream("in_" + b.lower(), 3, [(m, s, f) for m, s, f in ing], ev["start"][b][0], b != "SUN"))
    # marks: eclipses and super moons, keyed by phase-event index
    pm = [m for m, _ in ev["phases"]]
    marks: dict[int, list[int]] = {}
    kinds = {("solar", "partial"): 1, ("solar", "annular"): 2, ("solar", "total"): 3,
             ("lunar", "penumbral"): 5, ("lunar", "partial"): 6, ("lunar", "total"): 7}
    import bisect
    for m, who, k in ev["eclipses"]:
        i = bisect.bisect_left(pm, m)
        i = min((j for j in (i - 1, i) if 0 <= j < len(pm)), key=lambda j: abs(pm[j] - m))
        want = 0 if who == "solar" else 2
        assert ev["phases"][i][1] == want, (m, who)
        off = m - pm[i]
        assert -128 <= off <= 127
        marks.setdefault(i, [0, 0])
        marks[i][0] |= kinds[(who, k)]
        marks[i][1] = off & 0xFF
    for m, q, _ in ev["super"]:
        i = pm.index(m)
        marks.setdefault(i, [0, 0])
        marks[i][0] |= 8
    mk: list[int] = []
    for i in sorted(marks):
        mk += le(i, 2) + marks[i]
    return S, mk


def main() -> int:
    fit = json.loads((OUT / "fit.json").read_text())
    ev = json.loads((OUT / "events.json").read_text())
    src, info = series_tables(fit)
    (OUT / "sky_tab.c").write_text(src)
    S, mk = event_tables(ev)
    # first-fit into 16 KiB banks
    banks: list[list[dict]] = []
    fill: list[int] = []
    items = sorted(S, key=lambda s: -s["bytes"]) + [dict(name="marks", bytes=len(mk))]
    for s in items:
        for bi, f in enumerate(fill):
            if f + s["bytes"] <= 16384:
                banks[bi].append(s)
                fill[bi] += s["bytes"]
                break
        else:
            banks.append([s])
            fill.append(s["bytes"])
    bank_of = {}
    for bi, bl in enumerate(banks):
        lines = [f"/* generated by gen_tables.py: sky event streams, ROM bank {BANK0 + bi}. Do not edit. */",
                 "#ifdef __SDCC", f"#pragma bank {BANK0 + bi}", "#endif", "#include <stdint.h>", ""]
        for s in bl:
            bank_of[s["name"]] = BANK0 + bi
            if s["name"] == "marks":
                lines.append(c_arr("uint8_t", "sky_marks", mk, 24))
            else:
                lines.append(c_arr("uint8_t", f"sky_{s['name']}_i", s["idx"], 20))
                lines.append(c_arr("uint8_t", f"sky_{s['name']}_d", s["dat"], 24))
        (OUT / f"sky_ev_b{BANK0 + bi}.c").write_text("\n".join(lines) + "\n")
    lines = ["/* generated by gen_tables.py: the sky event stream descriptors (bank 0). Do not edit. */",
             '#include "sky.h"', ""]
    for s in S:
        lines.append(f"extern const uint8_t sky_{s['name']}_i[], sky_{s['name']}_d[];")
    lines.append("extern const uint8_t sky_marks[];")
    lines.append(f"const sky_stream sky_streams[SKY_NSTREAM] = {{")
    for s in S:
        lines.append(f"  {{{bank_of[s['name']]}, {s['width']}, {s['flag']}, {s['kind']}, {s['state0']}, {s['n']}u, "
                     f"{s['bias']}ul, sky_{s['name']}_i, sky_{s['name']}_d}}, /* {s['name']} */")
    lines.append("};")
    lines.append(f"const uint8_t sky_marks_bank = {bank_of['marks']};")
    lines.append(f"const uint16_t sky_nmarks = {len(mk) // 4}u;")
    lines.append("const uint8_t *const sky_marks_p = sky_marks;")
    (OUT / "sky_ev.c").write_text("\n".join(lines) + "\n")
    hdr = ["/* generated by gen_tables.py. Do not edit. */"] + info["hdr"] + [f"#define SKY_NSTREAM {len(S)}"]
    for i, s in enumerate(S):
        hdr.append(f"#define SKY_S_{s['name'].upper()} {i}")
    (OUT / "sky_gen.h").write_text("\n".join(hdr) + "\n")
    rep = dict(streams=[{k: s[k] for k in ("name", "n", "width", "flag", "bias", "bytes")} for s in S],
               marks=len(mk) // 4, marks_bytes=len(mk), banks=[[s["name"] for s in b] for b in banks], bank_fill=fill,
               total_event_bytes=sum(s["bytes"] for s in S) + len(mk), **{k: v for k, v in info.items() if k != "hdr"})
    (OUT / "tables.json").write_text(json.dumps(rep, indent=1))
    print(f"series: {info['nang']} angles, {info['nterms']} terms; events: {rep['total_event_bytes']} bytes in "
          f"{len(banks)} banks {fill}")
    for s in rep["streams"]:
        print(f"  {s['name']:12s} n={s['n']:5d} w={s['width']} bias={s['bias']:6d} {s['bytes']:6d} B")
    print(f"  marks        n={rep['marks']:5d}         {rep['marks_bytes']:6d} B")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
