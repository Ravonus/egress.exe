"""Pack the baked short-wall columns (bake2 output) into ROM banks for walls_asm's baked path.

Per height h (1..HB-1) a block of 1024 entries ([t][u], t = (cell - 1) << 1 | side), each entry 2h slot-0 bytes at
a power-of-two stride (so no entry crosses a 256-byte page: the copy steps the source with inc e). Blocks are
laid largest first, each aligned to its own size, from bank WB0. Writes bankNN_wb.s files and wbt.inc (the per-h
table in ROM0: bank, address high byte, shift, slot-0 / slot-1 copy entry points).
"""
import argparse
import re
from pathlib import Path


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("out", type=Path)
    ap.add_argument("--bin", type=Path, required=True)
    ap.add_argument("--hb", type=int, default=16)
    ap.add_argument("--wb0", type=int, default=16)
    ap.add_argument("--tables", type=Path, required=True, help="tables2.c (T_VTOP)")
    ap.add_argument("--h", type=int, default=64, help="framebuffer rows (VIEW_H)")
    a = ap.parse_args()
    data = a.bin.read_bytes()
    hb = a.hb
    ent, off = {}, 0
    for h in range(hb):
        ent[h] = data[off: off + 1024 * 2 * h]
        off += 1024 * 2 * h
    assert off == len(data)
    stride = {h: 1 << (2 * h - 1).bit_length() for h in range(1, hb)}
    order = sorted(range(1, hb), key=lambda h: -stride[h])
    rom = bytearray()
    base = {}
    for h in order:
        size = 1024 * stride[h]
        assert len(rom) % size == 0 or size > 0x4000 and len(rom) % 0x4000 == 0
        base[h] = len(rom)
        blk = bytearray(size)
        for i in range(1024):
            e = ent[h][i * 2 * h: (i + 1) * 2 * h]
            blk[i * stride[h]: i * stride[h] + 2 * h] = e
        rom += blk
    nb = (len(rom) + 0x3FFF) // 0x4000
    for k in range(nb):
        chunk = rom[k * 0x4000: (k + 1) * 0x4000]
        n = a.wb0 + k
        lines = [f"; generated by pack_wb.py: baked short walls, part {k}", f"\t.module bank{n}_wb", f"\t.area _CODE_{n}",
                 f"_wb_bank{k}::"]
        for i in range(0, len(chunk), 32):
            lines.append("\t.db " + ",".join(f"0x{b:02X}" for b in chunk[i: i + 32]))
        (a.out / f"bank{n}_wb.s").write_text("\n".join(lines) + "\n")
    assert hb <= 16  # rows are h << 4
    m = re.search(r"T_VTOP\[256\] = \{([^}]*)\}", a.tables.read_text())
    vtop = [int(v) for v in m.group(1).replace("\n", "").split(",")]
    vh = a.h
    voff = 255 - (vh + 255) // 2
    vend = voff + vh
    t = ["; generated by pack_wb.py: per wall height h < HB (16-byte rows): bank, address high byte, shift,",
         "; dest offset (vt - VOFF) * 2, ray_cv, ray_fv, vt, bot, copy entries (slot 0, 1)",
         "\t.area _CODE", "_WBT::"]
    for h in range(hb):
        vt, bot = vtop[h], vtop[h] + h
        assert voff <= vt and bot <= vend, h
        cv = vh if vt <= voff else vh - (vt - voff)
        fv = vh if bot >= vend else bot - voff
        if h == 0:
            bk, ah, sh = 0, 0, 0
        else:
            g = base[h]
            bk, ah, sh = a.wb0 + (g >> 14), 0x40 | ((g >> 8) & 0x3F), stride[h].bit_length() - 1
        t.append(f"\t.db {bk}, 0x{ah:02X}, {sh}, {(vt - voff) * 2}, {cv}, {fv}, {vt}, {bot}")
        t.append(f"\t.dw wcp0_end - {3 * 2 * h}, wcp1_end - {6 * 2 * h}")
        t.append("\t.db 0, 0, 0, 0")
    t.append("_fill2_end::")
    (a.out / "wbt.inc").write_text("\n".join(t) + "\n")
    print(f"baked walls: HB {hb}, {len(rom)} bytes, {nb} banks from {a.wb0}")
    print(nb)


if __name__ == "__main__":
    main()
